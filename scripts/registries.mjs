// Writes registries for code that Vite doesn't build (the Worker is bundled by
// wrangler, which has no import.meta.glob): each lists the files in a folder,
// so adding a feature means adding a file, never editing a shared list.
// The output is gitignored; npm's pre-scripts and the Vite plugin run this.
//
//   src/skills/<name>/SKILL.md  →  src/shared/builtin-skills.gen.ts
//   worker/routes/<name>.ts     →  worker/routes.gen.ts

import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

export const SKILLS_DIR = join(root, "src/skills");
export const ROUTES_DIR = join(root, "worker/routes");

/** Built-in skills, in front matter `order` (then name), as SKILL.md text. */
async function skills() {
  const entries = await readdir(SKILLS_DIR, { withFileTypes: true });
  const files = [];
  for (const entry of entries.filter((e) => e.isDirectory())) {
    const text = await readFile(join(SKILLS_DIR, entry.name, "SKILL.md"), "utf8").catch(() => undefined);
    if (text === undefined) continue;
    const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---/);
    let order;
    try {
      order = Number((match && parse(match[1])?.order) ?? 1000);
    } catch (e) {
      throw new Error(`src/skills/${entry.name}/SKILL.md: ${e instanceof Error ? e.message : e}`);
    }
    files.push({ name: entry.name, order, text });
  }
  files.sort((a, b) => a.order - b.order || a.name.localeCompare(b.name));
  return files;
}

/** Writes `text` to `path` unless it already holds it, so watchers don't rebuild for nothing. */
async function update(path, text) {
  const target = join(root, path);
  await mkdir(dirname(target), { recursive: true });
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== text) await writeFile(target, text);
}

/** Worker route modules, by file name. Each default-exports a list of routes (worker/route.ts). */
async function routes() {
  const names = (await readdir(ROUTES_DIR)).filter((n) => /^[\w-]+\.ts$/.test(n) && !n.endsWith(".test.ts")).sort();
  return [
    "// Generated by scripts/registries.mjs from worker/routes/*.ts. Don't edit; add a file there instead.",
    'import type { Route } from "./route";',
    ...names.map((n, i) => `import r${i} from "./routes/${n.replace(/\.ts$/, "")}";`),
    "",
    `export const ROUTES: Route[] = [${names.map((_, i) => `...r${i}`).join(", ")}];`,
    "",
  ].join("\n");
}

let queue = Promise.resolve();

/** Regenerates every registry. Calls run one after another, so a slower, older run can't overwrite a newer one. */
export function writeRegistries() {
  const run = queue.then(generate);
  queue = run.catch(() => {});
  return run;
}

async function generate() {
  await update("worker/routes.gen.ts", await routes());
  const list = await skills();
  const out = [
    "// Generated by scripts/registries.mjs from src/skills/*/SKILL.md. Don't edit; add a folder there instead.",
    "export const BUILTIN_SKILL_FILES: string[] = [",
    ...list.map((s) => `  ${JSON.stringify(s.text)},`),
    "];",
    "",
  ].join("\n");
  await update("src/shared/builtin-skills.gen.ts", out);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) await writeRegistries();
